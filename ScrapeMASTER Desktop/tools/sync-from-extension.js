/* Copies the parts the desktop app shares with the Chrome extension, so there is ONE source of truth:
 *   ../ScrapeMASTER/content.js     -> scraper/page-scraper.js  (page-side scraping, runs inside the Google view)
 *   ../ScrapeMASTER/background.js  -> engine/emails.js         (website email finder)
 *   ../ScrapeMASTER/geo-data.js    -> geo-data.js              (India states > districts > pincodes)
 * Run `npm run sync` after changing any of those in the extension.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ext = path.join(__dirname, '..', '..', 'ScrapeMASTER');
const root = path.join(__dirname, '..');
const read = f => fs.readFileSync(path.join(ext, f), 'utf8');
const write = (f, s) => { fs.mkdirSync(path.dirname(path.join(root, f)), { recursive: true }); fs.writeFileSync(path.join(root, f), s); };

// ---- page scraper: everything in content.js before the chrome.runtime wiring (runOnce) ----
{
  const src = read('content.js');
  const cut = src.indexOf('async function runOnce()');
  if (cut < 0) throw new Error('content.js: runOnce() marker not found');
  const body = src.slice(0, cut);
  const out =
    '// GENERATED by tools/sync-from-extension.js from ScrapeMASTER/content.js - do not edit by hand.\n' +
    '// Evaluated inside the Google view; resolves to {leads, businessCount, noPhone, signature, hasNext, captcha, url}.\n' +
    '(async () => {\n' + body + '\n' +
    '  var res = await scanWithPatience();\n' +
    '  return {\n' +
    '    leads: res.leads, businessCount: res.businessCount, noPhone: res.noPhone, signature: res.signature,\n' +
    '    hasNext: hasNextPage(), captcha: detectCaptcha(res.businessCount), url: location.href\n' +
    '  };\n' +
    '})()\n';
  write('scraper/page-scraper.js', out);
}

// ---- email finder: the pure block of background.js ----
{
  const src = read('background.js');
  const a = src.indexOf('const EMAIL_CONCURRENCY');
  const b = src.indexOf('async function endRun');
  if (a < 0 || b < 0) throw new Error('background.js: email section markers not found');
  let block = src.slice(a, b);
  block = block.replace(/async function hasWebPermission\(\)[\s\S]*?\n}\n/, '');   // chrome.permissions: extension only
  const out =
    '// GENERATED by tools/sync-from-extension.js from ScrapeMASTER/background.js - do not edit by hand.\n' +
    "'use strict';\n" +
    block + '\n' +
    'module.exports = { findEmailForSite, findContactForSite, extractEmails, extractMobiles, extractPhones, phoneOf, extractSocials, mobileOf, parseAddress, cleanSiteUrl, safeSiteUrl, EMAIL_RE_FULL, EMAIL_CONCURRENCY };\n';
  write('engine/emails.js', out);
}

// ---- geo data ----
write('geo-data.js', read('geo-data.js'));
console.log('synced scraper/page-scraper.js, engine/emails.js, geo-data.js');

// ---- UI stylesheet shared with the popup ----
fs.copyFileSync(path.join(ext, 'popup.css'), path.join(root, 'renderer', 'popup.css'));
console.log('synced renderer/popup.css');
